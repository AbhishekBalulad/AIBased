/**
 * AI Job Fraud Detection & Risk Scoring Engine
 * Analyzes job text features for suspicious patterns, fee requests, unrealistic salaries, and suspicious URLs.
 */
class FraudDetectionEngine {
  analyzeJobListing(jobData) {
    const textToAnalyze = `${jobData.title} ${jobData.description} ${jobData.salaryRange} ${jobData.companyName} ${jobData.officialApplyUrl} ${jobData.contactEmail}`.toLowerCase();

    let score = 0;
    const suspiciousIndicators = [];
    const safetyWarnings = [];

    // Indicator 1: Request for money or registration fee
    if (
      textToAnalyze.includes('registration fee') ||
      textToAnalyze.includes('security deposit') ||
      textToAnalyze.includes('pay fee') ||
      textToAnalyze.includes('send upi') ||
      textToAnalyze.includes('pay before') ||
      textToAnalyze.includes('charge for kit')
    ) {
      score += 45;
      suspiciousIndicators.push('Asks for upfront registration fee or security deposit');
      safetyWarnings.push('NEVER pay money to secure a job application. Legitimate employers never request upfront security deposits or application fees.');
    }

    // Indicator 2: Unrealistic salary claims for low-skill tasks
    if (
      textToAnalyze.includes('earn 1,00,000') ||
      textToAnalyze.includes('earn 50,000 weekly') ||
      textToAnalyze.includes('typing captchas') ||
      textToAnalyze.includes('easy money') ||
      textToAnalyze.includes('daily cash')
    ) {
      score += 25;
      suspiciousIndicators.push('Unrealistic salary claims for basic typing/data entry work');
      safetyWarnings.push('Be cautious of offers promising extraordinarily high income for simple online typing tasks.');
    }

    // Indicator 3: Suspicious contact email (e.g. gmail/yahoo for corporate job)
    if (
      jobData.contactEmail &&
      (jobData.contactEmail.includes('@gmail.com') ||
       jobData.contactEmail.includes('@yahoo.com') ||
       jobData.contactEmail.includes('@hotmail.com')) &&
      !jobData.companyName.toLowerCase().includes('freelance')
    ) {
      score += 15;
      suspiciousIndicators.push('Uses free personal email address (e.g. Gmail) instead of corporate domain');
      safetyWarnings.push('Verify employer identity if communication comes from a free webmail account.');
    }

    // Indicator 4: Suspicious application link
    if (
      jobData.officialApplyUrl &&
      (!jobData.officialApplyUrl.startsWith('https://') ||
       jobData.officialApplyUrl.includes('temp-website') ||
       jobData.officialApplyUrl.includes('pay-now') ||
       jobData.officialApplyUrl.includes('free-job'))
    ) {
      score += 20;
      suspiciousIndicators.push('Application link uses non-standard or unsecure domain URL');
      safetyWarnings.push('Do not enter personal bank details on non-HTTPS or suspicious domain links.');
    }

    // Indicator 5: Extreme urgency / pressure language
    if (
      textToAnalyze.includes('urgent requirement') ||
      textToAnalyze.includes('immediate joining today') ||
      textToAnalyze.includes('limited slots left')
    ) {
      score += 10;
      suspiciousIndicators.push('Uses high-pressure or extreme urgency phrases');
    }

    // Deduct risk if source is verified official government portal (e.g. SSC, NCS, Ministry)
    if (
      jobData.companyName.toLowerCase().includes('ministry') ||
      jobData.companyName.toLowerCase().includes('staff selection commission') ||
      jobData.companyName.toLowerCase().includes('department of') ||
      (jobData.officialApplyUrl && jobData.officialApplyUrl.includes('.gov.in'))
    ) {
      score = Math.max(0, score - 30);
    }

    // Determine Risk Level Classification
    let riskLevel = 'Low Risk';
    if (score >= 65) {
      riskLevel = 'High Risk';
    } else if (score >= 30) {
      riskLevel = 'Medium Risk';
    }

    // Generate Explanation
    let riskExplanation = 'This job listing originates from a verified public sector source or official portal.';
    if (riskLevel === 'High Risk') {
      riskExplanation = 'CRITICAL WARNING: This listing exhibits strong indicators of fraudulent activity, including requests for money or suspicious payment links.';
    } else if (riskLevel === 'Medium Risk') {
      riskExplanation = 'MODERATE CAUTION: This listing contains elements that require careful verification before sharing sensitive personal details.';
    }

    if (safetyWarnings.length === 0) {
      safetyWarnings.push('Always apply directly via official employer career portals.');
    }

    return {
      fraudRiskScore: Math.min(100, score),
      riskLevel,
      suspiciousIndicators,
      riskExplanation,
      safetyWarnings,
      legalDisclaimer: 'Notice: Fraud risk scores are generated by automated AI algorithms and heuristics. This assessment serves as a safety guidance tool and does not constitute guaranteed legal or factual proof of fraud.'
    };
  }
}

module.exports = new FraudDetectionEngine();
